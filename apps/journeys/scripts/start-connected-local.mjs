import { existsSync } from 'node:fs';
import { verifiedConnectedArtifact } from './connected-build-identity.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnvFile } from 'node:process';
import { execFileSync, spawn } from 'node:child_process';
import { verifyTestTarget } from './verify-test-target.mjs';
import {randomBytes} from 'node:crypto';
const app=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
loadEnvFile(path.join(app,'.env.test')); const target=verifyTestTarget();
const db=JSON.parse(execFileSync('docker',['inspect',target.dbContainer],{encoding:'utf8'}))[0];
if(db.Config.Labels['com.supabase.cli.project']!==target.projectRef||!db.State.Running||!existsSync(path.join(app,'.next/BUILD_ID')))throw Error('Owned local stack and current production build required');
const artifact=process.env.KINNSO_TASK10A_ATTESTED==='1'?verifiedConnectedArtifact(app):null;
const env={...process.env,KINNSO_LOCAL_BUILD_IDENTITY:artifact?JSON.stringify(artifact):'',KINNSO_ENVIRONMENT:'local',KINNSO_MEDIA_RUNTIME:'unified',KINNSO_SUPABASE_SECRET_KEY:process.env.SUPABASE_SERVICE_ROLE_KEY,KINNSO_SITE_URL:'http://127.0.0.1:3495',KINNSO_AUTH_RECOVERY_SECRET:randomBytes(32).toString('base64url')};
if(artifact)env.KINNSO_ENABLED_CAPABILITIES=[env.KINNSO_ENABLED_CAPABILITIES,'pilot'].filter(Boolean).join(',');
const child=spawn(process.execPath,[path.join(app,'node_modules/next/dist/bin/next'),'start','--hostname','127.0.0.1','--port','3495'],{cwd:app,env,stdio:'inherit',windowsHide:true});
for(const signal of ['SIGTERM','SIGINT'])process.on(signal,()=>child.kill(signal));
child.on('exit',code=>process.exitCode=code??1);
